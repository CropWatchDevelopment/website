	</p>

	<h2>霜が降りやすい条件</h2>
	<p>
		霜は、<strong>よく晴れて風の弱い夜</strong>に起こりやすくなります。雲がないと地面の熱が空へ逃げる「放射冷却」が強まり、風がないと冷えた空気が地表近くにたまるためです。最も冷え込むのは、日の出前の明け方です。
	</p>
	<p>
		天気予報の気温は、地上約1.5mの高さで測った値です。地面や作物の近くはそれより低くなることが多く、予報の最低気温が0℃より上でも、作物の高さでは氷点下になることがあります。気象台が発表する霜注意報も目安になりますが、畑ごとの冷え込み方は地形によって大きく変わります。
	</p>

	<h2>作物の高さで測る</h2>
	<p>
		霜対策の温度センサーは、<strong>守りたい作物の高さ</strong>に設置します。冷たい空気は低い場所に流れてたまるため、畑の中でも窪地や斜面の下側は冷え込みやすくなります。圃場が広い場合や高低差がある場合は、冷えやすい場所に追加で置くと安心です。
	</p>
	<ul>
		<li>露地野菜：作物の葉の高さ</li>
		<li>果樹園：花やつぼみのある高さ</li>
		<li>ハウス：作物の高さで、出入口や暖房機の風が直接当たらない場所</li>
	</ul>

	<h2>しきい値は余裕をもって決める</h2>
	<p>
		作物が傷み始める温度は、作物の種類や生育ステージで変わります。開花期や新芽の時期は特に弱くなります。地域の普及指導センターやJAが示す目安を参考に、<strong>危険な温度より数℃高い温度</strong>でアラートが鳴るように設定しましょう。通知を受けてから対策を始めるまでの時間を見込んでおくことが大切です。
	</p>
	<p>
		「注意」と「危険」の2段階でしきい値を設けると、注意で準備を始め、危険で対策を実行する、という使い分けができます。
	</p>

	<h2>ハウスでは暖房機の停止にも気づける</h2>
	<p>
		ハウス栽培では、外の冷え込みそのものより、<strong>暖房機の故障・燃料切れ・停電</strong>で温度が下がることが大きなリスクです。夜間に暖房が止まっても、温度アラートがあればすぐに気づけます。同じセンサーで、日中の高温や換気の閉め忘れも見張れます。
	</p>

	<h2>記録を次のシーズンに生かす</h2>
	<p>
		温度の記録が残っていれば、どの場所が、どんな夜に、どこまで冷え込んだかを振り返れます。冷えやすい場所に防霜ファンを増やす、被覆を早めに始めるなど、次のシーズンの対策を具体的に決められます。
	</p>

	<h2>よくある質問</h2>
	<h3>天気予報の最低気温だけでは不十分ですか？</h3>
	<p>
		予報は地上約1.5mの気温で、地域全体の目安です。作物の高さや窪地は予報より低くなることが多いため、畑ごとの実測が確実です。
	</p>
	<h3>電源のない畑でもセンサーを使えますか？</h3>
	<p>
		電池式のワイヤレスセンサーであれば、電源や配線のない畑や果樹園にも設置できます。屋外で使う場合は、防水・防塵のケースに入っているかを確認しましょう。
	</p>
	<h3>夜中に通知が来ても気づけるか心配です</h3>
	<p>
		メールに加えて、スマホのプッシュ通知など、音で気づける通知を使うのがおすすめです。家族や従業員など複数の人に通知を送れるようにしておくと安心です。
	</p>

