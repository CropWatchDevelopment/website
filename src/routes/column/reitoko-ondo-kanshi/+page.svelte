		結論から言うと、−40℃前後の冷凍庫を監視するセンサーは「−40℃まで測れる」だけでは足りません。<strong>測定範囲・低温での精度と校正・無線の届き方・霜や結露への強さ・アラートの設定</strong>の5点を確認すると、導入後の「つながらない」「誤報が多い」を防げます。
	</p>

	<h2>冷凍庫の温度監視が難しい理由</h2>
	<p>
		冷凍庫は、温度センサーにとって最も厳しい場所のひとつです。低温では電池の性能が落ちやすく、扉の開け閉めのたびに霜や結露が発生します。さらに、プレハブ冷凍庫や業務用冷凍庫の壁は断熱材を金属パネルで挟んだ構造のため、扉を閉めると無線の電波が外へ届きにくくなります。冷蔵庫ではうまく動いた機器が、冷凍庫では記録が途切れるのはこのためです。
	</p>

	<h2>ポイント1：測定範囲に余裕があるか</h2>
	<p>
		一般的な業務用冷凍庫は−18℃以下、急速冷凍庫（ショックフリーザー）は運転中に−30〜−40℃前後まで下がります。設定温度ぎりぎりの測定範囲では、下限に張りついて正しい値が取れません。<strong>使う温度帯より下に余裕のある測定範囲</strong>を選びましょう。
	</p>
	<p>
		なお、マグロなどに使われる−60℃前後の超低温冷凍庫は、一般的な温度センサーの範囲を超えます。超低温に対応した専用のセンサーが必要です。
	</p>

	<h2>ポイント2：低温での精度と校正証明書</h2>
	<p>
		HACCPの記録や取引先の監査では、「その温度計は正しいのか」を説明できることが大切です。カタログの精度の数字に加えて、次の点を確認します。
	</p>
	<ul>
		<li><strong>校正証明書が付くか</strong>：1台ごとの証明書があれば、監査でそのまま提示できます。</li>
		<li><strong>校正の温度点</strong>：常温の1点だけでなく、複数の温度点で校正されているか。</li>
		<li><strong>校正機関</strong>：ISO/IEC 17025の認定を受けた機関での校正かどうか。</li>
	</ul>

	<h2>ポイント3：金属の壁を越えて無線が届くか</h2>
	<p>
		冷凍庫の中のセンサーから外へデータを送るには、電波の届き方が重要です。Wi-Fi（2.4GHz帯）は金属や厚い断熱壁に弱く、冷凍庫の中では接続が不安定になりがちです。920MHz帯を使う<a class="extlink" href="https://lora-alliance.org/" target="_blank" rel="noopener noreferrer">LoRaWAN<sup class="reg">®</sup></a>は、少ない電力で遠くまで届き、扉のすき間や建物の構造を回り込みやすいのが特長です。
	</p>
	<p>
		もうひとつの備えが、<strong>通信が途切れたときにセンサー本体に記録を残せるか</strong>です。本体のメモリに保存し、通信が戻ったら自動で送り直す仕組みなら、記録に穴が空きません。
	</p>

	<h2>ポイント4：霜・結露・低温に耐えるつくり</h2>
	<p>
		扉を開けるたびに暖かい空気が入り、センサーの表面に霜や結露がつきます。水分が中に入ると故障の原因になるため、<strong>防塵・防水ケース（IP66など）</strong>に入っているかを確認しましょう。電池寿命は「常温での最長値」で書かれていることが多いので、冷凍庫での使用を前提にした条件かどうかも聞いておくと安心です。
	</p>

	<h2>ポイント5：霜取り運転を考えたアラート設定</h2>
	<p>
		冷凍庫は、霜取り運転（デフロスト）や扉の開け閉め、品出しのたびに、一時的に温度が上がります。しきい値を超えた瞬間に通知する設定だと、こうした正常な変化でもアラートが鳴り、やがて誰も通知を見なくなります。
	</p>
	<ul>
		<li>しきい値は、管理基準（例：−18℃）より少し余裕をもたせる</li>
		<li>「何分続いたら通知するか」を決めて、短時間の上昇は無視する</li>
		<li>夜間・休日に誰へ通知するかを決めておく</li>
	</ul>

	<h2>センサーの置き場所</h2>
	<p>
		冷気の吹き出し口の真正面や、扉のすぐそばは温度の変化が大きく、庫内の状態を正しく表しません。商品が置かれている高さで、庫内の代表的な場所に設置します。大型のプレハブ冷凍庫では、奥と手前など複数の場所に置くと、温度のむらにも気づけます。
	</p>

	<h2>よくある質問</h2>
	<h3>冷蔵庫用の温度センサーを冷凍庫で使っても大丈夫ですか？</h3>
	<p>
		測定範囲が冷凍庫の温度に対応していれば測定はできますが、低温での電池の持ちや、金属の壁越しの通信が問題になることがあります。冷凍庫での使用を前提にした機器を選ぶのが確実です。
	</p>
	<h3>停電や通信断のあいだの記録はどうなりますか？</h3>
	<p>
		機器によって異なります。本体のメモリに記録を保存し、復旧後に自動で送信する機器であれば、その間の記録も残ります。導入前に必ず確認しましょう。
	</p>
	<h3>急速冷凍庫でも使えますか？</h3>
	<p>
		−40℃前後まで測定できるセンサーであれば、多くの急速冷凍庫の温度帯に対応できます。−60℃前後の超低温冷凍庫には、専用のセンサーが必要です。
	</p>

