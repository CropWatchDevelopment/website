	<h2>Article 4 (Management and Protection of Personal Information)</h2>
	<p>
		Personal Information will be managed strictly and, except in the circumstances listed below,
		will not be disclosed or provided to any third party without the User’s consent. The Company
		also takes preventive and corrective measures against risks such as unauthorized access to,
		loss, destruction, alteration, or leakage of Personal Information, with due regard for security.
	</p>
	<ul class="list-legal">
		<li>
			(1) When it is necessary to protect a person’s life, body, or property and it is difficult to
			obtain the User’s consent.
		</li>
		<li>
			(2) When it is especially necessary to improve public health or promote the sound growth of
			children and it is difficult to obtain the User’s consent.
		</li>
		<li>
			(3) When it is necessary to cooperate with a national government body, local government, or a
			person entrusted by either of them in performing duties prescribed by laws and regulations,
			and obtaining the User’s consent is likely to impede the performance of those duties.
		</li>
		<li>(4) When otherwise permitted by laws and regulations.</li>
	</ul>

