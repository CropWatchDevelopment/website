	<ul class="list-legal">
		<li>
			1. The User may request that the Company cease using, erase, or cease providing to third
			parties the Personal Information it holds (collectively, “Cessation of Use, etc.”).
		</li>
		<li>
			2. Upon receiving a request under the preceding paragraph, the Company will conduct the
			necessary investigation. If it determines that the request has grounds, it will carry out the
			Cessation of Use, etc. However, if the Cessation of Use, etc. would involve substantial cost
			or is otherwise difficult, and the Company can take an alternative measure necessary to
			protect the User’s rights and interests, it will take that alternative measure.
		</li>
		<li>
			3. When the Company decides whether to carry out the Cessation of Use, etc. under the
			preceding paragraph, it will contact the User.
		</li>
	</ul>

