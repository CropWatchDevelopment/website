	<h2>Article 6 (Disclosure of Personal Information)</h2>
	<p>
		A User may request that the Company disclose Personal Information it holds. When the Company
		receives such a request from a User, it will disclose the information to the User without delay.
		However, the Company may withhold all or part of the information if disclosure would result in
		any of the following circumstances. If the Company decides not to disclose the information, it
		will notify the User of that decision without delay.
	</p>
	<ul class="list-legal">
		<li>
			(1) There is a risk of harming the life, body, property, or other rights or interests of the
			User or a third party
		</li>
		<li>
			(2) There is a risk of materially interfering with the proper conduct of the Company’s
			business
		</li>
		<li>(3) Disclosure would otherwise violate a law or regulation</li>
	</ul>

	<hr />

	<h2>Article 7 (Correction, etc. of Personal Information)</h2>
	<ul class="list-legal">
		<li>
			1. If Personal Information held by the Company is incorrect, the User may request that the
			Company correct, add to, or delete that Personal Information (collectively, “Correction,
			etc.”).
