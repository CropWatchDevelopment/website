		<li>
			2. Upon receiving a request under the preceding paragraph, the Company will conduct the
			necessary investigation without delay. If it determines that the request has grounds, it will
			make the Correction, etc. without delay.
		</li>
		<li>
			3. When the Company decides whether to make a Correction, etc. under the preceding paragraph,
			it will contact the User without delay.
		</li>
	</ul>

