	<h2>Article 5 (Outsourcing the Handling of Personal Information)</h2>
	<p>
		The Company may outsource all or part of the handling of Personal Information to the extent
		necessary to achieve the purposes of use. In that case, the Company will carefully assess the
		service provider’s qualifications, include confidentiality and other relevant provisions in the
		agreement, and exercise necessary and appropriate supervision over the service provider.
	</p>

